#!/usr/bin/env python3
"""
Builds the community window's own sprites, scui_*, into UIAtlases/UIAtlas from the Survivor UI kit
at UIDesigner/survivor-ui-assets/survivor-ui. Run:  python Tools/import_ui_assets.py

WHY THIS MOD HAS AN ATLAS AT ALL (2026-09-25): the community window was rebuilt on the user's
premium reference (Tools/generate_community_ui.py). It picks every plate by a scui_* name, so it is
whole on its own; a skin mod that ships the same names later in the load order (AshfallUI's
tools/make_community.py) restyles it with no XML - exactly how SurvivorOrigins' sui_* art works.

The art carries its own colour, so every element drawn with it is tinted [white], and a state is a
sprite swap, never a tint. The kit's border_lbrt is LEFT, BOTTOM, RIGHT, TOP; NGUI's settings take
left/right/top/bottom - remapped explicitly below.
"""

import colorsys
import io
import json
import os

from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
MOD = os.path.dirname(HERE)
ATLAS = os.path.join(MOD, "UIAtlases", "UIAtlas")
KIT = os.environ.get("SURVIVOR_UI_KIT", os.path.join(
    "F:", os.sep, "Game Related Programs", "Creation Stuff", "7 days to die mods",
    "UIDesigner", "survivor-ui-assets", "survivor-ui"))

# sprite -> (kit asset or None when drawn, why)
SPRITES = [
    ("scui_window", "modal", "every plate: the window and its panels"),
    ("scui_row", "skill_row_normal", "a member row at rest"),
    ("scui_row_hover", "skill_row_hover", "a member row under the pointer"),
    ("scui_row_selected", "skill_row_selected", "the selected member's row"),
    ("scui_row_thin", "milestone_unlocked", "the thin rows: skills, traits, the search field"),
    ("scui_btn", "button_normal", "a button at rest"),
    ("scui_btn_hover", "button_hover", "a button under the pointer"),
    ("scui_btn_danger", None, "Remove from community, and the beds callout: button_normal with a red rim"),
    ("scui_bar_track", "bar_track", "a bar's groove"),
    ("scui_bar_frame", None, "a bar's rim, drawn over its fill"),
    ("scui_fill_good", "fill_food", "the morale fills (green)"),
    ("scui_fill_skill", "fill_durability", "the skill fills (amber)"),
    ("scui_fill_health", "fill_health", "the health fill (red)"),
    ("scui_portrait", "slot_normal", "the frame round a portrait"),
    ("scui_divider", "divider", "a section rule"),
]
BAD_HUE = 0.02
FRAME_RIM = (183, 165, 138, 255)          # the kit's rim colour, #B7A58A

HEAD = """<?xml version="1.0" encoding="UTF-8"?>
<!-- 9-slice metadata for this folder's sprites, read by UIAtlasFromFolder.loadSpriteSettings.
     GENERATED by Tools/import_ui_assets.py from the Survivor UI kit's manifest. -->
<sprites>
"""


def _red_rim(img):
    """The plate with every warm, saturated pixel - its rim - turned red, lightness kept."""
    im = img.convert("RGBA")
    px = im.load()
    for y in range(im.size[1]):
        for x in range(im.size[0]):
            r, g, b, a = px[x, y]
            h, s, v = colorsys.rgb_to_hsv(r / 255.0, g / 255.0, b / 255.0)
            if a and s > 0.22 and v > 0.18 and (h < 0.17 or h > 0.95):
                r2, g2, b2 = colorsys.hsv_to_rgb(BAD_HUE, min(1.0, s * 1.1), v)
                px[x, y] = (int(r2 * 255), int(g2 * 255), int(b2 * 255), a)
    return im


def _frame(w=64, h=16, rim=2):
    """A bar's rim: a 2-pixel border in the kit's rim colour with a clear middle."""
    im = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    ImageDraw.Draw(im).rectangle([0, 0, w - 1, h - 1], outline=FRAME_RIM, width=rim)
    return im


def main():
    if not os.path.isdir(KIT):
        raise SystemExit("kit not found at %s\n(set SURVIVOR_UI_KIT to its survivor-ui folder)" % KIT)
    by_id = {a["id"]: a for a in json.load(io.open(os.path.join(KIT, "manifest.json"), encoding="utf-8"))["assets"]}
    os.makedirs(ATLAS, exist_ok=True)

    def kit(aid):
        return Image.open(os.path.join(KIT, by_id[aid]["png"].replace("/", os.sep))).convert("RGBA")

    def borders(aid):
        l, b, r, t = by_id[aid]["border_lbrt"]
        return l, r, t, b

    rows = []
    for name, aid, why in SPRITES:
        if name == "scui_btn_danger":
            im, lrtb = _red_rim(kit("button_normal")), borders("button_normal")
        elif name == "scui_bar_frame":
            im, lrtb = _frame(), (3, 3, 3, 3)
        else:
            im, lrtb = kit(aid), borders(aid)
        im.save(os.path.join(ATLAS, name + ".png"))
        rows.append('\t<sprite name="%s" borderleft="%d" borderright="%d" bordertop="%d" borderbottom="%d"/>  <!-- %s -->\n'
                    % ((name,) + lrtb + (why,)))
        print("  %-20s %4dx%-4d borders l%d r%d t%d b%d" % ((name, im.size[0], im.size[1]) + lrtb))
    io.open(os.path.join(ATLAS, "settings.xml"), "w", encoding="utf-8", newline="\n").write(HEAD + "".join(rows) + "</sprites>\n")
    print("  %d sprite(s) in UIAtlases/UIAtlas" % len(rows))


if __name__ == "__main__":
    main()
