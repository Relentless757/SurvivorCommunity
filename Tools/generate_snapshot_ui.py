#!/usr/bin/env python3
"""
Generates the survivor snapshot, windowScSnapshot, into Config/XUi_InGame/windows.xml between its GENERATED
markers (added before </configs> the first time). Run from anywhere:  python Tools/generate_snapshot_ui.py

The card XUiC_ScSnapshot fills while the player talks to a survivor (the user's design, 2026-10-07, after State of
Decay 2's card, without its standing bar):

    +------------------------------+
    | NAME (title bar)    [portrait]|
    | Medic               [        ]|
    | + 100 / 130        (face) Happy|
    | > 120 / 120                    |
    | TRAITS ----------------------- |
    |  . Optimist  (or ????)         |
    | SKILLS ----------------------- |
    | [ico] Cardio      * * * . . . .|
    |  ... Wits, Fighting, Shooting  |
    | [ico] Medicine    * * . . . . .|
    +------------------------------+

It sits in the vanilla "dialog" window group (xui.xml), on the left of the screen: anchor Bottom, its right edge left
of the spoken-line strip (screen centre +-376, SCore puts the NPC's line there), of XNPCCore's voice-subtitle box
(windowNPCSubtitles: a dark panel, centre +-400, 94..250 up) and of the face the dialog camera centres on, its bottom
at the XP bar's line (AshfallUI's track tops out 108 above the screen bottom; the bar itself is hidden while a
dialog is open). At 1080p (1529 units wide) its left edge is 8 units from the screen edge.

Rules (the community window's): every plate is a scui_* sprite handed [white] (AshfallUI ships premium art under the
same names); icons are vanilla menu symbols or SC's scui_mood_* faces; no [darkGrey]/menu_empty plate or boxbg, which
AshfallUI's dialog dressing would take over; the portrait texture has no texture=/textures=/autounload attribute.
"""

import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MOD = os.path.dirname(HERE)
TARGET = os.path.join(MOD, "Config", "XUi_InGame", "windows.xml")
BEGIN = "\t<!-- GENERATED:BEGIN scsnapshot (Tools/generate_snapshot_ui.py) -->"
END = "\t<!-- GENERATED:END scsnapshot -->"
CONTROLLER = "SurvivorCommunity.ScSnapshot, SurvivorCommunity"

W, H = 352, 520
STRIP_HALF = 376          # the spoken-line strip: screen centre +-376
VOICE_HALF = 400          # XNPCCore's voice-subtitle box: screen centre +-400, up to 250 above the bottom
GAP = 4
BOTTOM = 112              # just above AshfallUI's XP track (96..108 above the screen bottom)
POS_X = -(max(STRIP_HALF, VOICE_HALF) + GAP + W)
POS_Y = BOTTOM + H
DEPTH = 6

TITLE = "226,219,203,255"
BODY = "226,220,208,255"
DIM = "190,182,166,255"
GOLD = "206,178,120,255"

SKILLS = (("ui_game_symbol_cardio", "scSkillCardio"),
          ("ui_game_symbol_intellect", "scSkillWits"),
          ("ui_game_symbol_melee", "scSkillFighting"),
          ("ui_game_symbol_rifle", "scSkillShooting"))
TRAIT_ROWS = 3
TRAIT_TOP, TRAIT_STEP = 204, 26
SKILL_TOP, SKILL_H, SKILL_STEP = 324, 34, 38
STARS, STAR_X, STAR_STEP, STAR_SIZE = 7, 176, 22, 20


def plate(sprite, x, y, w, h, depth=0, extra=""):
    return ('<sprite depth="%d" sprite="%s" type="sliced" color="[white]" pos="%d,%d" width="%d" height="%d"%s/>'
            % (depth, sprite, x, y, w, h, (" " + extra) if extra else ""))


def icon(sprite, cx, cy, size, depth=3, color="[white]", extra=""):
    return ('<sprite depth="%d" sprite="%s" pos="%d,%d" width="%d" height="%d" pivot="center" color="%s"%s/>'
            % (depth, sprite, cx, cy, size, size, color, (" " + extra) if extra else ""))


def label(x, y, w, h, size, color, text=None, key=None, extra=""):
    t = ('text="%s"' % text) if text is not None else ('text_key="%s"' % key)
    return ('<label depth="4" pos="%d,%d" width="%d" height="%d" font_size="%d" %s color="%s"%s/>'
            % (x, y, w, h, size, t, color, (" " + extra) if extra else ""))


def skill_row(i, sprite, name_line):
    y = SKILL_TOP + i * SKILL_STEP
    o = [plate("scui_row_thin", 16, -y, W - 32, SKILL_H, depth=1),
         icon(sprite, 36, -(y + SKILL_H // 2), 22),
         name_line(y)]
    for j in range(STARS):
        cx = STAR_X + j * STAR_STEP + STAR_SIZE // 2
        o.append(icon("ui_game_symbol_star", cx, -(y + SKILL_H // 2), STAR_SIZE, color="{snapsk%dstar%d}" % (i, j + 1)))
    return o


def build():
    o = ['\t<!-- The survivor snapshot, GENERATED by Tools/generate_snapshot_ui.py - edit that, not this. In the vanilla',
         '\t     "dialog" window group (xui.xml); XUiC_ScSnapshot fills it while the player talks to a survivor. -->',
         '\t<append xpath="/windows">',
         '\t\t<window name="windowScSnapshot" anchor="Bottom" pos="%d,%d" width="%d" height="%d" depth="%d" '
         'controller="%s" cursor_area="false">' % (POS_X, POS_Y, W, H, DEPTH, CONTROLLER),
         '\t\t\t<rect depth="0" name="panel" pos="0,0" width="%d" height="%d" visible="{snapvisible}">' % (W, H)]
    body = [plate("scui_window", 0, 0, W, H),
            # title bar and name, the portrait on its right like the reference's photo
            plate("scui_row_selected", 8, -8, W - 16, 56, depth=1),
            label(20, -14, W - 144, 44, 32, TITLE, text="{snapname}", extra='upper_case="true"'),
            plate("scui_portrait", W - 116, -6, 104, 104, depth=3),
            icon("ui_game_symbol_player", W - 64, -58, 56, depth=4, extra='visible="{snapnoportrait}"'),
            '<texture depth="5" name="snapPortrait" pos="%d,-14" width="88" height="88" visible="{snaphasportrait}"/>' % (W - 108),
            label(20, -70, W - 144, 26, 20, GOLD, text="{snaprole}"),
            # health, stamina, mood
            icon("ui_game_symbol_add", 32, -118, 24),
            label(52, -106, 128, 26, 22, BODY, text="{snaphealth} / {snaphealthmax}"),
            icon("ui_game_symbol_run", 32, -150, 24),
            label(52, -138, 128, 26, 22, BODY, text="{snapstamina} / {snapstaminamax}"),
            icon("{snapmoodicon}", 204, -136, 32),
            label(226, -124, W - 240, 26, 22, "{snapmoodcolor}", text="{snapmoodword}"),
            # traits
            label(16, -172, 200, 24, 20, TITLE, key="scUiTraits", extra='upper_case="true"'),
            plate("scui_divider", 16, -196, W - 32, 3, depth=1)]
    for k in range(TRAIT_ROWS):
        y = TRAIT_TOP + k * TRAIT_STEP
        body += ['<rect depth="1" visible="{snaptrait%dvisible}">' % (k + 1),
                 "\t" + icon("ui_game_filled_circle", 26, -(y + 12), 6, color=DIM),
                 "\t" + label(38, -y, W - 54, 24, 18, BODY, text="{snaptrait%d}" % (k + 1)),
                 "</rect>"]
    body += [label(16, -292, 200, 24, 20, TITLE, key="scUiSkills", extra='upper_case="true"'),
             plate("scui_divider", 16, -316, W - 32, 3, depth=1)]
    for i, (sprite, key) in enumerate(SKILLS):
        body += skill_row(i, sprite, lambda y, k=key: label(56, -(y + 6), 112, 24, 18, BODY, key=k))
    spec = skill_row(len(SKILLS), "{snapspecicon}", lambda y: label(56, -(y + 6), 112, 24, 18, BODY, text="{snapspecname}"))
    body += ['<rect depth="1" visible="{snapspecvisible}">'] + ["\t" + s for s in spec] + ["</rect>"]
    o += ["\t\t\t\t" + line for line in body]
    o += ["\t\t\t</rect>", "\t\t</window>", "\t</append>"]
    return "\n".join(o) + "\n"


def main():
    with io.open(TARGET, "r", encoding="utf-8", newline="") as f:
        text = f.read()
    if "\r\n" in text:
        raise SystemExit("REFUSING: %s has CRLF lines; this generator writes LF like the rest of the file." % TARGET)
    block = BEGIN + "\n" + build() + END + "\n"
    if BEGIN in text and END in text:
        text = text.split(BEGIN)[0] + block + text.split(END)[1].lstrip("\n")
    else:
        if text.count("</configs>") != 1:
            raise SystemExit("REFUSING: expected one </configs> in %s" % TARGET)
        text = text.replace("</configs>", "\n" + block + "</configs>")
    with io.open(TARGET, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    last = SKILL_TOP + len(SKILLS) * SKILL_STEP + SKILL_H
    print("generate_snapshot_ui: wrote windowScSnapshot %dx%d at pos %d,%d (bottom %d), last row ends at %d"
          % (W, H, POS_X, POS_Y, BOTTOM, last))
    assert last + 8 <= H, "the skill rows run past the card"
    assert TRAIT_TOP + TRAIT_ROWS * TRAIT_STEP <= 292, "the traits run into the skills heading"
    assert STAR_X + STARS * STAR_STEP <= W - 16, "the stars run past the row"


if __name__ == "__main__":
    main()
